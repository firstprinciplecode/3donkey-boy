/**
 * Writes roblox/src/shared/Levels.luau from the authored web levels, so both builds play the same
 * pyramids. Editor paint (tiers, neon) is web-only and left out. Run: npm run export:roblox-levels
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { AUTHORED_LEVELS } from '../src/levels/defs';
import type { LevelDef } from '../src/levels/types';

const OUT = fileURLToPath(new URL('../roblox/src/shared/Levels.luau', import.meta.url));
const SKIP = new Set(['tiers', 'neon']);
const NAMES = ['MEADOW', 'CANDY', 'DESERT', 'HARVEST', 'FROST', 'TOMB', 'VOLCANO'];

function luau(value: unknown, indent: string): string {
  if (typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return '{}';
    const inline = value.map((entry) => luau(entry, indent));
    const flat = `{ ${inline.join(', ')} }`;
    if (flat.length <= 90 && !flat.includes('\n')) return flat;
    const inner = `${indent}\t`;
    return `{\n${value.map((entry) => `${inner}${luau(entry, inner)},`).join('\n')}\n${indent}}`;
  }
  if (value && typeof value === 'object') {
    const fields = Object.entries(value).filter(([, v]) => v !== undefined);
    const inline = fields.map(([k, v]) => `${key(k)} = ${luau(v, indent)}`);
    const flat = `{ ${inline.join(', ')} }`;
    if (flat.length <= 90 && !flat.includes('\n')) return flat;
    const inner = `${indent}\t`;
    return `{\n${fields.map(([k, v]) => `${inner}${key(k)} = ${luau(v, inner)},`).join('\n')}\n${indent}}`;
  }
  throw new Error(`cannot write ${String(value)}`);
}

function key(name: string): string {
  return /^[A-Za-z_]\w*$/.test(name) ? name : `[${JSON.stringify(name)}]`;
}

/** Luau tables are 1-based, so lock ladder indexes shift by one. */
function forRoblox(def: LevelDef): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(def)) if (!SKIP.has(k)) out[k] = v;
  out.locks = def.locks.map((lock) => ({ ...lock, ladder: lock.ladder + 1 }));
  return out;
}

if (AUTHORED_LEVELS.length !== NAMES.length) throw new Error('name every level in NAMES');
const blocks = AUTHORED_LEVELS.map((def, i) => {
  const body = Object.entries(forRoblox(def))
    .map(([k, v]) => `\t${key(k)} = ${luau(v, '\t')},`)
    .join('\n');
  return `local ${NAMES[i]} = {\n${body}\n}`;
});

writeFileSync(
  OUT,
  `-- Generated by scripts/export-roblox-levels.ts from src/levels/defs.ts. Do not edit by hand.
-- Spots are { ring, side, offset }: side 0..3 is the south, east, north and west face, and offset is
-- measured from the middle of that side. Lock ladder indexes are 1-based here.

${blocks.join('\n\n')}

-- Played in order, then loop with rising speed.
return { ${NAMES.join(', ')} }
`,
);
console.log(`wrote ${OUT}`);
